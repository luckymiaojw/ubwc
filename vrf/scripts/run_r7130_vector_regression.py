def run_cmd(cmd: list[str], log_file: Path | None = None) -> int:
    print("+", " ".join(shlex.quote(x) for x in cmd), flush=True)
    if log_file:
        log_file.parent.mkdir(parents=True, exist_ok=True)
        with log_file.open("a") as fh:
            proc = subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT)
            return proc.returncode
    return subprocess.run(cmd).returncode


def run_make(target: str, top: str, build_root: Path, flags: str, run_args: str, log: Path) -> int:
    make_cmd = (
        f"source {shlex.quote(str(ENV_SCRIPT))}; "
        f"make -C {shlex.quote(str(SIM_DIR))} "
        f"TOP={shlex.quote(top)} "
        f"BUILD_ROOT={shlex.quote(str(build_root))} "
        f'TB_PARAM_FLAGS="{flags}" '
        f'RUN_ARGS="{run_args}" '
        f"{target}"
    )
    return run_cmd(["tcsh", "-c", make_cmd], log)


def prepare_otf_stream(case: VectorCase,
                       build_dir: Path,
                       expected_y: Path | None = None,
                       expected_uv: Path | None = None) -> None:
    out = build_dir / "input_otf_stream.txt"
    expected_y = expected_y or case.linear_y
    expected_uv = expected_uv or case.linear_uv
    if case.fmt in ("rgba8888", "rgba1010102"):
        cmd = [
            sys.executable, str(OTF_CASE_TOOL), "gen-stream",
            "--format", case.fmt,
            "--expected", str(expected_y),
            "--width", str(case.width),
            "--stored-height", str(case.height),
            "--out", str(out),
        ]
    else:
        phase_arg = "--p010-uv-phase" if case.fmt == "p010" else "--nv12-uv-phase"
        cmd = [
            sys.executable, str(OTF_CASE_TOOL), "gen-stream",
            "--format", case.fmt,
            "--expected-y", str(expected_y),
            "--expected-uv", str(expected_uv),
            "--width", str(case.width),
            "--stored-y-height", str(case.height),
            "--stored-uv-height", str(case.active_uv_height),
            phase_arg, "even",
            "--out", str(out),
        ]
    subprocess.check_call(cmd)


def prepare_enc_files(case: VectorCase, build_dir: Path) -> None:
    build_dir.mkdir(parents=True, exist_ok=True)
    write_words64(build_dir / "expected_tile_plane0.memh", active_linear_words(case, 0))
    write_words64(build_dir / "expected_meta_plane0.memh",
                  normalize_enc_meta_words(case, 0, load_words64(case.meta_y)))
    strip_at_lines(case.tile_comp_y, build_dir / "expected_cmp_plane0.memh")
    if case.has_uv:
        write_words64(build_dir / "expected_tile_plane1.memh", active_linear_words(case, 1))
        write_words64(build_dir / "expected_meta_plane1.memh",
                      normalize_enc_meta_words(case, 1, load_words64(case.meta_uv)))
        strip_at_lines(case.tile_comp_uv, build_dir / "expected_cmp_plane1.memh")
    prepare_otf_stream(case, build_dir)


def prepare_dec_files(case: VectorCase, build_dir: Path) -> None:
    build_dir.mkdir(parents=True, exist_ok=True)
    strip_at_lines(case.meta_y, build_dir / "input_meta_plane0.txt")
    strip_at_lines(case.tile_comp_y, build_dir / "input_tile_plane0.txt")
    strip_at_lines(case.tile_uncomp_y, build_dir / "inject_tile_plane0.txt")
    if case.has_uv:
        strip_at_lines(case.meta_uv, build_dir / "input_meta_plane1.txt")
        strip_at_lines(case.tile_comp_uv, build_dir / "input_tile_plane1.txt")
        strip_at_lines(case.tile_uncomp_uv, build_dir / "inject_tile_plane1.txt")
    else:
        for name in ("input_meta_plane1.txt", "input_tile_plane1.txt", "inject_tile_plane1.txt"):
            (build_dir / name).write_text("")
    if case.lossy and case.fmt in ("rgba8888", "rgba1010102"):
        expected_linear_y = build_dir / "expected_linear_from_uncompressed_plane0.memh"
        write_words64(expected_linear_y, dec_tile_to_linear_words(case, 0))
        prepare_otf_stream(case, build_dir, expected_y=expected_linear_y)
    else:
        prepare_otf_stream(case, build_dir)
    shutil.copy2(build_dir / "input_otf_stream.txt", build_dir / "expected_otf_stream.txt")


def copy_waves(build_dir: Path, archive: Path, prefix: str) -> None:
    archive.mkdir(parents=True, exist_ok=True)
    for fsdb in build_dir.glob("*.fsdb"):
        shutil.copy2(fsdb, archive / f"{prefix}_{fsdb.name}")


def log_has_failure(log: Path) -> bool:
    if not log.exists():
        return True
    text = log.read_text(errors="ignore")
    return bool(re.search(r"(^|[ \t])FAIL:|\[TB\]\[ERROR\]|\$fatal|Fatal:", text, re.M))


def run_one(kind: str, case: VectorCase, root: Path, archive: Path) -> bool:
    top = ENC_TOP if kind == "enc" else DEC_TOP
    build_root = root / kind / case.name
    build_dir = build_root / f"{top}_fake"
    log = build_root / "run_full.log"
    flags = make_param_flags(top, case, dec=(kind == "dec"))
    run_args = "+tb_frame_repeat=1 +tb_timeout_cycles=80000000 +tb_idle_gap_cycles=12000000"

    if kind == "enc":
        prepare_enc_files(case, build_dir)
    else:
        prepare_dec_files(case, build_dir)

    rc = run_make("comp", top, build_root, flags, run_args, log)
    if rc == 0:
        rc = run_make("run", top, build_root, flags, run_args, log)
    copy_waves(build_dir, archive, f"{kind}_{case.name}")
    passed = rc == 0 and not log_has_failure(build_dir / "run.log") and not log_has_failure(log)
    print(f"[{'PASS' if passed else 'FAIL'}] {kind} {case.name}", flush=True)
    return passed


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--enc-only", action="store_true")
    ap.add_argument("--dec-only", action="store_true")
    ap.add_argument("--smoke", action="store_true", help="Run only the first vector directory.")
    ap.add_argument("--case", action="append", default=[], help="Run cases whose directory-derived name contains this text.")
    ap.add_argument("--source-tag", default="r7130", help="Vector source tag, e.g. r7130 or r7928.")
    ap.add_argument("--keep-root", type=Path)
    args = ap.parse_args()

    source_tag = args.source_tag.strip().lower()
    if not re.fullmatch(r"[a-z0-9_]+", source_tag):
        ap.error("--source-tag may only contain lowercase letters, digits, and underscore")
    cases = [load_case(p) for p in sorted(VECTOR_ROOT.glob(f"enc_from_{source_tag}_pattern_*"))]
    if args.smoke:
        cases = [case for case in cases if case.name.startswith("256x160_rgba8888")][:1]
    if args.case:
        cases = [case for case in cases if any(token in case.name for token in args.case)]
    kinds = ["enc", "dec"]
    if args.enc_only:
        kinds = ["enc"]
    if args.dec_only:
        kinds = ["dec"]

    ts = _dt.datetime.now().strftime(f"{source_tag}_%Y%m%d_%H%M%S")
    root = args.keep_root or (SIM_DIR / "build" / ts)
    archive = root / "waves"
    summary = root / "summary.txt"
    root.mkdir(parents=True, exist_ok=True)

    total = 0
    passed = 0
    failed: list[str] = []
    for case in cases:
        for kind in kinds:
            total += 1
            if run_one(kind, case, root, archive):
                passed += 1
            else:
                failed.append(f"{kind}:{case.name}")

    summary.write_text(
        f"total={total}\npass={passed}\nfail={len(failed)}\n"
        f"root={root}\nwaves={archive}\n"
        + "".join(f"FAIL {item}\n" for item in failed)
    )
    print(f"SUMMARY total={total} pass={passed} fail={len(failed)}")
    print(f"RUN_ROOT={root}")
    print(f"WAVE_ARCHIVE={archive}")
    print(f"SUMMARY_FILE={summary}")
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())
